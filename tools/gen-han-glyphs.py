#!/usr/bin/env python3
"""Rasterize CJK into 5×5 / 7×7 pixel glyphs for pixelfx (Latin mini/big rhythm)."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CHARS_PATH = ROOT / "tools" / "han-chars-ember.txt"
OUT_PATH = ROOT / "src" / "core" / "font-han-data.js"

FONT_CANDIDATES = [
    "/System/Library/Fonts/PingFang.ttc",
    "/System/Library/Fonts/STHeiti Light.ttc",
    "/Library/Fonts/Arial Unicode.ttf",
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
]

_font_cache: dict[int, ImageFont.FreeTypeFont] = {}


def load_font(px: int) -> ImageFont.FreeTypeFont:
    if px in _font_cache:
        return _font_cache[px]
    for path in FONT_CANDIDATES:
        if Path(path).is_file():
            _font_cache[px] = ImageFont.truetype(path, px)
            return _font_cache[px]
    raise SystemExit("No CJK font found for glyph generation")


def raster(ch: str, cell: int, font_px: int) -> str:
    img = Image.new("L", (cell, cell), 0)
    draw = ImageDraw.Draw(img)
    font = load_font(font_px)
    bbox = draw.textbbox((0, 0), ch, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    x = (cell - tw) // 2 - bbox[0]
    y = (cell - th) // 2 - bbox[1]
    draw.text((x, y), ch, fill=255, font=font)
    rows = []
    for r in range(cell):
        row = "".join("#" if img.getpixel((c, r)) > 72 else "." for c in range(cell))
        rows.append(row)
    return "|".join(rows)


def table_lines(name: str, cell: int, font_px: int, chars: str) -> list[str]:
    lines = [f"export const {name} = {{"]
    for ch in chars:
        esc = ch.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  "{esc}": "{raster(ch, cell, font_px)}",')
    lines.append("};")
    return lines


def main() -> None:
    chars = CHARS_PATH.read_text(encoding="utf-8")
    text = "\n".join(
        ["// Auto-generated by tools/gen-han-glyphs.py — do not edit by hand."]
        + table_lines("HAN5", 5, 9, chars)
        + [""]
        + table_lines("HAN7", 7, 12, chars)
        + [""]
    )
    OUT_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {OUT_PATH} ({len(chars)} chars)")


if __name__ == "__main__":
    main()
