#!/usr/bin/env python3
"""Import separate, unarmed DNF frames into editable JS pixels. PNGs are build inputs only."""
import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source', type=Path, default=ROOT.parent / 'dnf_art_refs/spriters_resource')
parser.add_argument('--ember', type=Path, default=ROOT.parent / 'ember-echo')
args = parser.parse_args()
manifest = json.loads((args.ember / 'assets/heroes/manifest.json').read_text())
# Keep existing palette indices stable for the game's wardrobe editor.
palettes = [json.loads(value) for value in re.findall(r'^    palette: (\{[^\n]+\}),$', (args.ember / 'src/hero-pixel-data.js').read_text(), re.M)]
BODY_PATHS = [
    '03_时装_二觉/Male Slayer (Blade Master)__206523/A Type',
    '03_时装_二觉/Male Slayer (Berserker)__206520/A Type',
    '03_时装_二觉/Female Slayer (Sword Master)__206536/A Type',
    '01_角色职业_一觉/Female Mage (Elementalist)__198254/A Type',
    '01_角色职业_一觉/Male Mage (Elemental Bomber)__198232/A Type',
]
# Hand guides in each untrimmed body's source coordinates, authored on the action contact sheet.
GUIDES = [
    {'idle': [31,55], 'walk': [83,66], 'attack1': [31,55], 'attack2': [121,69], 'attack3': [110,68], 'cast': [96,76], 'hurt': [88,73], 'dead': [77,120]},
    {'idle': [38,61], 'walk': [85,69], 'attack1': [38,61], 'attack2': [130,69], 'attack3': [118,67], 'cast': [107,76], 'hurt': [90,74], 'dead': [78,120]},
    {'idle': [53,139], 'walk': [63,143], 'attack1': [105,112], 'attack2': [78,117], 'attack3': [52,105], 'cast': [55,75], 'hurt': [68,126], 'dead': [74,174]},
    {'idle': [49,56], 'walk': [95,42], 'attack1': [61,57], 'attack2': [61,57], 'attack3': [78,9], 'cast': [78,9], 'hurt': [64,58], 'dead': [87,82]},
    {'idle': [85,64], 'walk': [85,64], 'attack1': [126,56], 'attack2': [126,56], 'attack3': [87,48], 'cast': [87,48], 'hurt': [92,58], 'dead': [99,112]},
]
ANGLES = [2.1, 2.1, 0.65, -1.45, -1.45]

def colors_at(image):
    colors = defaultdict(list)
    for y in range(image.height):
        for x in range(image.width):
            color = image.getpixel((x,y))
            if color[3]: colors[color].append((x,y))
    return colors

def align(body, combined):
    """Register identical visible body pixels; restore the weapon-occluded pixels from body."""
    bp, cp = colors_at(body), colors_at(combined)
    votes = Counter()
    for color in sorted(set(bp) & set(cp), key=lambda c:len(bp[c])*len(cp[c]))[:12]:
        if len(bp[color])*len(cp[color]) > 6000: continue
        for x,y in bp[color]:
            for xx,yy in cp[color]: votes[(xx-x,yy-y)] += 1
    pixels = [(x,y,color) for color, positions in bp.items() for x,y in positions]
    def score(shift):
        dx,dy = shift
        return sum(0 <= x+dx < combined.width and 0 <= y+dy < combined.height and combined.getpixel((x+dx,y+dy)) == color for x,y,color in pixels) / len(pixels)
    return max((score(shift), shift) for shift,_ in votes.most_common(12))

output = ['// Unarmed source frames, generated by tools/import-dnf-bodies.py. No PNG at runtime.\n', 'export const HERO_PIXEL_DATA = {\n']
reports = []
for index,(look, body_path, palette) in enumerate(zip(manifest, BODY_PATHS, palettes)):
    collected = {}; scores = []
    frame_ids = sorted(set(frame for clip in look['clips'].values() for frame in clip))
    for frame_id in frame_ids:
        body_file = args.source / body_path / f'{frame_id:03d}.png'
        combined_file = args.source / look['source']['path'] / f'{frame_id:03d}.png'
        body = Image.open(body_file).convert('RGBA'); combined = Image.open(combined_file).convert('RGBA')
        score,(dx,dy) = align(body, combined)
        # Some weapon exports duplicate animation frames and shift subsequent frame IDs.
        # Register by identical body pixels instead of assuming the file numbers still match.
        if score < 0.7:
            candidates = [(score, (dx,dy), body, body_file)]
            for delta in range(-12,13):
                candidate_file = args.source / body_path / f'{frame_id+delta:03d}.png'
                if delta == 0 or not candidate_file.exists(): continue
                candidate = Image.open(candidate_file).convert('RGBA')
                similarity, shift = align(candidate, combined)
                candidates.append((similarity, shift, candidate, candidate_file))
            score,(dx,dy),body,body_file = max(candidates, key=lambda entry:entry[0])
        scores.append(score)
        if score < 0.55: raise ValueError(f'{look["id"]}/{frame_id}: ambiguous frame registration ({score:.3f})')
        box = body.getbbox(); cropped = body.crop(box)
        frame_offset = [box[0] + dx - look['source']['anchor'][0], box[1] + dy - look['source']['anchor'][1]]
        kind = next(kind for kind,clip in look['clips'].items() if frame_id in clip)
        guide = GUIDES[index][kind]
        # Follow small frame-to-frame hand movement by snapping to the nearest occupied body pixel.
        gx,gy = guide
        candidates = [( (x-gx)**2+(y-gy)**2, x,y) for color,pts in colors_at(body).items() for x,y in pts]
        _,gx,gy = min(candidates)
        grip = [gx + dx - look['source']['anchor'][0], gy + dy - look['source']['anchor'][1]]
        for color in set(cropped.getdata()):
            if color[3]:
                value = '#' + ''.join(f'{v:02x}' for v in color)
                if value not in palette.values(): palette[f'{len(palette):02x}'] = value
        collected[frame_id] = (cropped, frame_offset, grip, score, body_file.stem)
    by_color = {tuple(bytes.fromhex(color[1:])):key for key,color in palette.items()}
    output.append('  '+json.dumps(look['id'])+': {\n    palette: '+json.dumps(palette,separators=(',',':'))+',\n    frames: {\n')
    report = {'id': look['id'], 'bodySource': body_path, 'combinedSource': look['source']['path'], 'frames': {}}
    for frame_id,(im,offset,grip,score,body_frame_id) in collected.items():
        rows = [''.join(by_color[im.getpixel((x,y))] if im.getpixel((x,y))[3] else '..' for x in range(im.width)).rstrip('.') for y in range(im.height)]
        output.append(f'      "{frame_id}": {{ width: {im.width}, height: {im.height}, offset: {json.dumps(offset)}, grip: {json.dumps(grip)}, angle: {ANGLES[index]}, layers: [{{ id: "body", rows: [\n')
        output.extend('        '+json.dumps(row)+',\n' for row in rows)
        output.append('      ] }] },\n')
        report['frames'][str(frame_id)] = {'bodyFrame':body_frame_id, 'sha256':hashlib.sha256(bytes(channel for pixel in im.getdata() for channel in (pixel if pixel[3] else (0,0,0,0)))).hexdigest(), 'offset':offset, 'grip':grip, 'registration':round(score,4)}
    output.append('    },\n  },\n'); reports.append(report)
    print(look['id'],len(frame_ids),'unarmed frames; minimum registration',round(min(scores),3))
output.append('};\n')
(ROOT/'src/core/dnf-pixel-data.js').write_text(''.join(output))
(ROOT/'tools/dnf-body-sources.json').write_text(json.dumps(reports,ensure_ascii=False,indent=2)+'\n')
